# Converts the PlastiBytes logo and the CITS mark into 1-bit C arrays for the ePaper.
# Usage: python make_logos.py  -> writes firmware/epaper-panel/src/logos.h
from PIL import Image

ROBOT_SAVE = r"C:\petra-system\firmware\robot_save.jpg"
WEB = r"C:\Users\UNESCO\AppData\Local\Temp\claude\C--Users-UNESCO-Downloads-PETra-Sytems\e62057ad-1f79-4922-9c11-60df7a444ece\scratchpad\web"
OUT = r"C:\petra-system\firmware\epaper-panel\src\logos.h"


def to_bits(img, width, crop_box=None, white_above=235):
    im = Image.open(img).convert("RGBA")
    if crop_box:
        im = im.crop(crop_box)
    im = im.crop(im.getbbox())  # trim transparent margins
    h = round(im.height * width / im.width)
    im = im.resize((width, h), Image.LANCZOS)
    rows = []
    for y in range(h):
        row = bytearray((width + 7) // 8)
        for x in range(width):
            r, g, b, a = im.getpixel((x, y))
            lum = (r * 77 + g * 150 + b * 29) >> 8
            if a > 110 and lum < white_above:  # anything visible and not white -> black
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(row)
    return width, h, b"".join(rows)


def c_array(name, w, h, data):
    lines = [f"// {w}x{h}, 1 = black, MSB first",
             f"constexpr int {name}_W = {w};", f"constexpr int {name}_H = {h};",
             f"const uint8_t {name}[] PROGMEM = {{"]
    for i in range(0, len(data), 20):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
    lines.append("};\n")
    return "\n".join(lines)


parts = ["// Generated by make_logos.py from plastibytes.com and citscm.com logos. Do not edit.",
         "#pragma once", "#include <Arduino.h>", ""]
parts.append(c_array("LOGO_PB_LARGE", *to_bits(WEB + r"\logoplas.png", 360)))
parts.append(c_array("LOGO_PB_SMALL", *to_bits(WEB + r"\logoplas.png", 150)))
# CITS: only the coloured mark (its lettering is white). The mark is the left part of the image.
im = Image.open(WEB + r"\cits.png")
parts.append(c_array("LOGO_CITS", *to_bits(WEB + r"\cits.png", 70, (0, 0, int(im.width * 0.36), im.height))))
# Robot Save partner logo, same height as the small PlastiBytes logo (footer)
parts.append(c_array("LOGO_ROBOT_SAVE", *to_bits(ROBOT_SAVE, 118, white_above=190)))
open(OUT, "w", encoding="utf-8").write("\n".join(parts))
print("wrote", OUT)
